package io.github.shangotek.glanceicons

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Test

class IconRulesTest {

    @Test
    fun `angular role suffix wins over the ts extension`() {
        assertEquals(FileIcon.COMPONENT, IconRules.fileIcon("user-card.component.ts"))
        assertEquals(FileIcon.SERVICE, IconRules.fileIcon("user.service.ts"))
        assertEquals(FileIcon.STORE, IconRules.fileIcon("users.store.ts"))
        assertEquals(FileIcon.TYPESCRIPT, IconRules.fileIcon("main.ts"))
    }

    @Test
    fun `spec of a component is a test`() {
        assertEquals(FileIcon.TEST, IconRules.fileIcon("user-card.component.spec.ts"))
    }

    @Test
    fun `longest suffix wins`() {
        assertEquals(FileIcon.ROUTES, IconRules.fileIcon("app-routing.module.ts"))
        assertEquals(FileIcon.CONFIG, IconRules.fileIcon("app.config.ts"))
    }

    @Test
    fun `exact names win over extensions`() {
        assertEquals(FileIcon.PACKAGE, IconRules.fileIcon("package.json"))
        assertEquals(FileIcon.NPM, IconRules.fileIcon("package-lock.json"))
        assertEquals(FileIcon.LOCK, IconRules.fileIcon("Cargo.lock"))
        assertEquals(FileIcon.JSON, IconRules.fileIcon("messages.de.json"))
    }

    @Test
    fun `matching ignores case`() {
        assertEquals(FileIcon.README, IconRules.fileIcon("README.md"))
        assertEquals(FileIcon.DOCKER, IconRules.fileIcon("Dockerfile"))
        assertEquals(FileIcon.LICENSE, IconRules.fileIcon("LICENSE"))
        assertEquals(FileIcon.PNG, IconRules.fileIcon("Logo.PNG"))
        assertEquals(FolderIcon.ASSETS, IconRules.folderIcon("Assets"))
    }

    @Test
    fun `prefixes cover file families`() {
        assertEquals(FileIcon.ENV, IconRules.fileIcon(".env.production"))
        assertEquals(FileIcon.TSCONFIG, IconRules.fileIcon("tsconfig.app.json"))
        assertEquals(FileIcon.DOCKER, IconRules.fileIcon("docker-compose.override.yml"))
    }

    @Test
    fun `angular 2025 style guide joins suffixes with a hyphen`() {
        assertEquals(FileIcon.GUARD, IconRules.fileIcon("auth-guard.ts"))
        assertEquals(FileIcon.PIPE, IconRules.fileIcon("date-de-pipe.ts"))
        assertEquals(FileIcon.INTERCEPTOR, IconRules.fileIcon("auth-interceptor.ts"))
        assertEquals(FileIcon.ROUTES, IconRules.fileIcon("user-resolver.ts"))
        assertEquals(FileIcon.ROUTES, IconRules.fileIcon("app-routing-module.ts"))
        assertEquals(FileIcon.TEST, IconRules.fileIcon("auth-guard.spec.ts"))
        // Components, directives and services have no suffix any more; AngularFiles reads their decorator.
        assertEquals(FileIcon.TYPESCRIPT, IconRules.fileIcon("user-card.ts"))
    }

    @Test
    fun `more angular files are recognised by name`() {
        assertEquals(FileIcon.MODULE, IconRules.fileIcon("shared.module.ts"))
        assertEquals(FileIcon.MODULE, IconRules.fileIcon("shared-module.ts"))
        assertEquals(FileIcon.ROUTES, IconRules.fileIcon("app-routing.module.ts"))
        assertEquals(FileIcon.MODEL, IconRules.fileIcon("user.model.ts"))
        assertEquals(FileIcon.MODEL, IconRules.fileIcon("role.enum.ts"))
        assertEquals(FileIcon.STORYBOOK, IconRules.fileIcon("button.stories.ts"))
        assertEquals(FileIcon.ENV, IconRules.fileIcon("environment.development.ts"))
        assertEquals(FileIcon.CONFIG, IconRules.fileIcon("proxy.conf.json"))
        // Server-side rendering files, as generated by `ng add @angular/ssr`
        assertEquals(FileIcon.ROUTES, IconRules.fileIcon("app.routes.server.ts"))
        assertEquals(FileIcon.CONFIG, IconRules.fileIcon("app.config.server.ts"))
        assertEquals(FileIcon.MODEL, IconRules.fileIcon("blog.data.ts"))
    }

    @Test
    fun `package managers and hosting get their logo`() {
        assertEquals(FileIcon.YARN, IconRules.fileIcon("yarn.lock"))
        assertEquals(FileIcon.PNPM, IconRules.fileIcon("pnpm-workspace.yaml"))
        assertEquals(FileIcon.BUN, IconRules.fileIcon("bun.lockb"))
        assertEquals(FileIcon.NX, IconRules.fileIcon("nx.json"))
        assertEquals(FileIcon.FIREBASE, IconRules.fileIcon("firebase.json"))
        assertEquals(FileIcon.VERCEL, IconRules.fileIcon("vercel.json"))
        assertEquals(FileIcon.NETLIFY, IconRules.fileIcon("netlify.toml"))
        assertEquals(FileIcon.GITLAB, IconRules.fileIcon(".gitlab-ci.yml"))
    }

    @Test
    fun `more languages get their logo`() {
        assertEquals(FileIcon.VUE, IconRules.fileIcon("App.vue"))
        assertEquals(FileIcon.SVELTE, IconRules.fileIcon("Counter.svelte"))
        assertEquals(FileIcon.GRAPHQL, IconRules.fileIcon("schema.graphql"))
        assertEquals(FileIcon.JUPYTER, IconRules.fileIcon("analysis.ipynb"))
        assertEquals(FileIcon.SWIFT, IconRules.fileIcon("App.swift"))
        assertEquals(FileIcon.DART, IconRules.fileIcon("main.dart"))
        assertEquals(FileIcon.PHP, IconRules.fileIcon("index.php"))
        assertEquals(FileIcon.RUBY, IconRules.fileIcon("Gemfile"))
        assertEquals(FileIcon.C, IconRules.fileIcon("main.c"))
        assertEquals(FileIcon.CPP, IconRules.fileIcon("main.cpp"))
        assertEquals(FileIcon.DOTNET, IconRules.fileIcon("Program.cs"))
        assertEquals(FileIcon.LUA, IconRules.fileIcon("init.lua"))
    }

    @Test
    fun `languages and frameworks get their logo`() {
        assertEquals(FileIcon.ANGULAR, IconRules.fileIcon("angular.json"))
        assertEquals(FileIcon.REACT, IconRules.fileIcon("App.tsx"))
        assertEquals(FileIcon.REACT, IconRules.fileIcon("Button.jsx"))
        assertEquals(FileIcon.TEST, IconRules.fileIcon("App.test.tsx"))
        assertEquals(FileIcon.NEXTJS, IconRules.fileIcon("next.config.mjs"))
        assertEquals(FileIcon.PYTHON, IconRules.fileIcon("main.py"))
        assertEquals(FileIcon.PYTHON, IconRules.fileIcon("requirements.txt"))
        assertEquals(FileIcon.JAVA, IconRules.fileIcon("Main.java"))
        assertEquals(FileIcon.KOTLIN, IconRules.fileIcon("App.kt"))
        assertEquals(FileIcon.RUST, IconRules.fileIcon("main.rs"))
        assertEquals(FileIcon.RUST, IconRules.fileIcon("Cargo.toml"))
        assertEquals(FileIcon.GO, IconRules.fileIcon("main.go"))
        assertEquals(FileIcon.GO_MOD, IconRules.fileIcon("go.mod"))
        assertEquals(FileIcon.DOCKER, IconRules.fileIcon("Dockerfile"))
    }

    @Test
    fun `config files show the tool they configure`() {
        assertEquals(FileIcon.ANGULAR, IconRules.fileIcon("angular.json"))
        assertEquals(FileIcon.TSCONFIG, IconRules.fileIcon("tsconfig.json"))
        assertEquals(FileIcon.ESLINT, IconRules.fileIcon("eslint.config.js"))
        assertEquals(FileIcon.PRETTIER, IconRules.fileIcon(".prettierrc"))
        assertEquals(FileIcon.VITE, IconRules.fileIcon("vite.config.ts"))
        assertEquals(FileIcon.VITEST, IconRules.fileIcon("vitest.config.ts"))
        assertEquals(FileIcon.TAILWIND, IconRules.fileIcon("tailwind.config.js"))
        assertEquals(FileIcon.EDITORCONFIG, IconRules.fileIcon(".editorconfig"))
        assertEquals(FileIcon.NODE, IconRules.fileIcon(".nvmrc"))
        assertEquals(FileIcon.NPM, IconRules.fileIcon(".npmrc"))
        assertEquals(FileIcon.CONFIG, IconRules.fileIcon("config.json"))
        assertEquals(FileIcon.CONFIG, IconRules.fileIcon("proxy.config.json"))
        assertEquals(FileIcon.CONFIG, IconRules.fileIcon("karma.conf.js"))
    }

    @Test
    fun `java and kotlin test classes are told apart by case`() {
        assertEquals(FileIcon.JAVA_TEST, IconRules.fileIcon("UserServiceTest.java"))
        assertEquals(FileIcon.JAVA_TEST, IconRules.fileIcon("CheckoutIT.java"))
        assertEquals(FileIcon.JAVA, IconRules.fileIcon("Contest.java"))
        assertEquals(FileIcon.KOTLIN_TEST, IconRules.fileIcon("AppTests.kt"))
        assertEquals(FileIcon.KOTLIN, IconRules.fileIcon("Latest.kt"))
    }

    @Test
    fun `each image format has its own icon`() {
        assertEquals(FileIcon.SVG, IconRules.fileIcon("logo.svg"))
        assertEquals(FileIcon.PNG, IconRules.fileIcon("logo.png"))
        assertEquals(FileIcon.JPG, IconRules.fileIcon("photo.jpeg"))
        assertEquals(FileIcon.GIF, IconRules.fileIcon("spinner.gif"))
        assertEquals(FileIcon.WEBP, IconRules.fileIcon("hero.webp"))
        assertEquals(FileIcon.FAVICON, IconRules.fileIcon("favicon.ico"))
        assertEquals(FileIcon.IMAGE, IconRules.fileIcon("scan.tiff"))
        assertEquals(FileIcon.VIDEO, IconRules.fileIcon("demo.mp4"))
        assertEquals(FileIcon.AUDIO, IconRules.fileIcon("jingle.mp3"))
        assertEquals(FileIcon.ARCHIVE, IconRules.fileIcon("release.tar.gz"))
        assertEquals(FileIcon.DOCUMENT, IconRules.fileIcon("notes.docx"))
    }

    @Test
    fun `common folders get icons`() {
        assertEquals(FolderIcon.APP, IconRules.folderIcon("app"))
        assertEquals(FolderIcon.CORE, IconRules.folderIcon("core"))
        assertEquals(FolderIcon.PAGES, IconRules.folderIcon("layout"))
        assertEquals(FolderIcon.ASSETS, IconRules.folderIcon("fonts"))
        assertEquals(FolderIcon.CONFIG, IconRules.folderIcon(".vscode"))
        assertEquals(FolderIcon.DIRECTIVES, IconRules.folderIcon("directives"))
        assertEquals(FolderIcon.PIPES, IconRules.folderIcon("pipes"))
        assertEquals(FolderIcon.GUARDS, IconRules.folderIcon("guards"))
        assertEquals(FolderIcon.INTERCEPTORS, IconRules.folderIcon("interceptors"))
        assertEquals(FolderIcon.BACKEND, IconRules.folderIcon("backend"))
        assertEquals(FolderIcon.BACKEND, IconRules.folderIcon("server"))
        assertEquals(FolderIcon.FRONTEND, IconRules.folderIcon("frontend"))
        assertEquals(FolderIcon.FRONTEND, IconRules.folderIcon("client"))
        assertEquals(FolderIcon.MODELS, IconRules.folderIcon("models"))
        assertEquals(FolderIcon.SHARED, IconRules.folderIcon("shared"))
        assertEquals(FolderIcon.UTILS, IconRules.folderIcon("utils"))
        assertEquals(FolderIcon.PAGES, IconRules.folderIcon("pages"))
    }

    @Test
    fun `unknown names keep the IDE icon`() {
        assertNull(IconRules.fileIcon("notes.txt"))
        assertNull(IconRules.fileIcon("Makefile"))
        assertNull(IconRules.fileIcon("build.gradle.kts"))
        assertNull(IconRules.folderIcon("misc"))
    }

    @Test
    fun `every icon has an svg`() {
        val paths = FileIcon.entries.map { it.path } + FolderIcon.entries.map { it.path }
        paths.forEach { assertNotNull("Missing $it", javaClass.getResource(it)) }
    }
}
